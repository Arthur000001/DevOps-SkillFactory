# --- Шаг 1: создание каталога для bind mount ---

mkdir -p /tmp/bind_test
# mkdir — команда для создания каталогов.
# Опция -p означает:
#   • Создавать родительские каталоги при необходимости.
#   • Если каталог уже существует — не выдавать ошибку.
# В итоге на хостовой машине будет создан каталог /tmp/bind_test.
# Мы используем /tmp, потому что это временная директория, доступная без особых прав.
# В дальнейшем этот каталог будет "примонтирован" внутрь контейнера.

# --- Шаг 2: создание тестовой HTML-страницы ---

echo "Hello from bind mount!" > /tmp/bind_test/index.html
# echo выводит строку "Hello from bind mount!".
# > — это оператор перенаправления вывода:
#   • Всё, что выводит echo, будет записано в файл.
#   • Если файл существует — он будет перезаписан.
# Здесь мы создаём файл index.html внутри каталога /tmp/bind_test.
# В итоге в этом файле будет простая HTML-страница (на самом деле просто текст, но nginx его отдаст как содержимое).

# --- Шаг 3: запуск контейнера nginx ---

docker run -d -p 8000:80 \
  --mount type=bind,src=/tmp/bind_test,dst=/usr/share/nginx/html/ \
  nginx
# docker run — команда для запуска нового контейнера.
# Опции:
#   • -d → запускаем в фоновом режиме (detached), чтобы контейнер не блокировал терминал.
#   • -p 8000:80 → пробрасываем порты:
#        - 8000 — порт на хостовой машине (куда ты будешь заходить через браузер).
#        - 80 — порт внутри контейнера (стандартный порт веб-сервера nginx).
#     То есть: обращаясь к http://localhost:8000, ты попадаешь на порт 80 внутри контейнера.
#
#   • --mount type=bind,src=/tmp/bind_test,dst=/usr/share/nginx/html/
#       - type=bind → используем bind mount (прямое подключение каталога хоста в контейнер).
#       - src=/tmp/bind_test → путь к каталогу на хосте (источник).
#       - dst=/usr/share/nginx/html/ → путь внутри контейнера (куда подмонтировать).
#     Nginx по умолчанию раздаёт файлы именно из /usr/share/nginx/html,
#     поэтому, подключив туда нашу папку, мы подменяем стандартное содержимое контейнера своим.
#
#   • nginx → имя образа, из которого создаётся контейнер.
#     Если образа нет локально, Docker автоматически скачает его с Docker Hub.
#
# В итоге: запускается nginx, который раздаёт содержимое /tmp/bind_test с хоста,
# и доступ к этому содержимому идёт по адресу http://localhost:8000.
